package com.hybridauth.api;

/**
 * Обработчик переноса данных другого мода (например, профиля SMPIdentity или питомцев).
 *
 * HybridAuth сам переносит файлы мира игрока, запись авторизации, whitelist, op и бан-лист.
 * Всё, что хранится по UUID в других модах, переносится через обработчики.
 *
 * Вызывается на потоке сервера, когда оба аккаунта вне сервера.
 * Если обработчик выбросил исключение, все уже выполненные шаги откатываются,
 * включая откат, который вернул этот обработчик раньше.
 */
public interface AccountTransferHandler {

    /** Имя для отчёта администратору, например "SMPIdentity". */
    String name();

    /**
     * Переносит данные. Должен атомарно перенести данные или выбросить исключение без изменений.
     *
     * @return действие, которое отменяет перенос (вызывается при откате всей операции)
     */
    Runnable transfer(AccountTransferPlan plan) throws Exception;
}
